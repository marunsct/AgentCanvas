#!/usr/bin/env bash
# Regenerates infra/schema.sql (the reference DDL) from a freshly migrated Postgres: `scripts/export_schema_sql.sh`.
# Needs Docker. Uses a throwaway pgvector container; nothing of yours is touched. The Alembic migrations stay the
# source of truth: this file is what they produce, for people who want to read the schema in one place.
set -euo pipefail
cd "$(dirname "$0")/.."
name=ac-schema-dump-$$
trap 'docker rm -f "$name" >/dev/null 2>&1 || true' EXIT
docker run -d --rm --name "$name" -e POSTGRES_PASSWORD=dump -e POSTGRES_USER=agentcanvas -e POSTGRES_DB=agentcanvas \
  -p 127.0.0.1::5432 pgvector/pgvector:pg16 >/dev/null
for _ in $(seq 1 60); do docker exec "$name" pg_isready -U agentcanvas -q 2>/dev/null && break; sleep 1; done
sleep 2
port=$(docker port "$name" 5432/tcp | head -1 | sed 's/.*://')
(cd apps/api && DATABASE_URL="postgresql://agentcanvas:dump@127.0.0.1:$port/agentcanvas" uv run alembic upgrade head >/dev/null)
{
  echo "-- AgentCanvas control database: the schema the Alembic migrations (apps/api/alembic/versions) produce on Postgres."
  echo "-- Generated by scripts/export_schema_sql.sh; do not edit by hand. The LangGraph checkpoint and store tables are"
  echo "-- created by LangGraph itself (.setup()) and are not listed here."
  docker exec "$name" pg_dump -U agentcanvas -d agentcanvas -s --no-owner --no-privileges --no-comments \
    | grep -v -E '^(SET |SELECT pg_catalog\.set_config|\\(un)?restrict)' | cat -s
} > infra/schema.sql
echo "infra/schema.sql: $(grep -c '^CREATE TABLE' infra/schema.sql) tables"
