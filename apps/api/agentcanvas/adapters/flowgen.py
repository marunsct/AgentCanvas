"""Workflow -> a Python module run by the flow engine (`supersteps`), for frameworks without a graph (S32).

The module reads like code a person would write with the framework: an agent builder per AI agent block, one
`async def` per block of the canvas (marked with `@canvas-node` so the code view jumps back to the block), and a
`FLOW` that says which step follows which. What is the framework's own (its imports, how an "Ask AI" step and an
agent are written) comes from a `Dialect`; everything else is shared by the frameworks that use it.
"""

from __future__ import annotations

import builtins
import json
import keyword
import re
from dataclasses import dataclass, field

from agentcanvas import designs
from agentcanvas.adapters.langchain.codegen import doc_line, one_line
from agentcanvas.adapters.openai_agents.codegen import _camel, _lit, _py, model_settings
from agentcanvas.ir.models import Node, Workflow

STEP_TYPES = {
    "core.set", "core.router", "core.join", "core.approval", "core.human_input", "core.script", "core.llm",
    "core.agent", "knowledge.search", "core.decide",
}  # fmt: skip
RESOURCE_TYPES = {"model.chat", "tool.python", "mw.model_call_limit"}
_TAKEN = {"rt", "Agent", "FunctionAgent", "NativeOutput", "BaseModel", "Field", "Any", "Literal", "FLOW",
          "annotations", "run", "state"}  # fmt: skip


@dataclass
class Agentic:
    """What a dialect needs to write one AI agent block."""

    name: str  # the agent's name
    model: str  # `run.model(...)`
    instructions: str  # the constant holding them
    tools: list[str]
    approve: list[str]
    answer: str  # the output class ("" for text answers)
    call_limit: int | None  # model calls in one turn (a model call limit block), else None
    fail_at_limit: bool


@dataclass
class Dialect:
    label: str  # "Pydantic AI"
    runtime_import: str
    imports: list[str]  # framework imports, always
    doc: str  # how the AI blocks are written, for the module docstring
    structured_imports: list[str] = field(default_factory=list)  # instead of `imports` when an agent has a typed answer
    agent_class: str = "Agent"  # what an agent builder returns

    def text_agent(self, name: str, model: str) -> str:
        raise NotImplementedError

    def agent(self, a: Agentic) -> tuple[list[str], str]:
        """(the `Agent(...)` arguments, the extra keywords of `run.agent(...)`)."""
        raise NotImplementedError


class _Names:
    def __init__(self) -> None:
        self.used: set[str] = set(_TAKEN)

    def take(self, wanted: str) -> str:
        name = re.sub(r"\W+", "_", wanted.strip()).strip("_") or "step"
        name = f"step_{name}" if name[0].isdigit() else name
        if keyword.iskeyword(name) or hasattr(builtins, name) or name in self.used or name.startswith("_"):
            name = f"{name.lstrip('_')}_step"
        base, i = name, 2
        while name in self.used:
            name, i = f"{base}{i}", i + 1
        self.used.add(name)
        return name


def generate(wf: Workflow, dialect: Dialect) -> str:
    names = _Names()
    fns = {n.id: names.take(n.name) for n in wf.nodes if n.type not in ("core.router", "core.join")}
    blocks: list[str] = []
    typing_names: set[str] = set()
    pydantic_names: set[str] = set()
    for n in wf.nodes:
        code, models = _step(wf, n, fns.get(n.id, ""), names, dialect)
        if code:
            blocks.append(code)
        if models:
            typing_names |= {t for t in ("Literal",) if re.search(rf"\b{t}\[", models)}
            pydantic_names |= {"BaseModel"} | ({"Field"} if "Field(" in models else set())
    structured = bool(pydantic_names)
    head = [
        f'"""{doc_line(wf.name)}: a {dialect.label} flow, generated by AgentCanvas.',
        "",
        "Each block of the canvas is one step below (its id is in the `@canvas-node` comment), and FLOW at the end",
        f"says which step follows which. {dialect.doc} The other blocks are plain Python. `run` gives each step its",
        "models, tools and knowledge bases, and asks people when a step needs them. Change the workflow on the canvas",
        "and generate it again rather than editing this file.",
        '"""',
        "",
        "from typing import " + ", ".join(sorted({"Any", *typing_names})),
        "",
        *(dialect.structured_imports if structured and dialect.structured_imports else dialect.imports),
        *([f"from pydantic import {', '.join(sorted(pydantic_names))}"] if pydantic_names else []),
        "",
        dialect.runtime_import,
    ]
    return "\n".join(head) + "\n\n\n" + "\n\n\n".join([*blocks, _flow(wf, fns)]) + "\n"


def _marker(n: Node) -> str:
    return f"# ── @canvas-node {one_line(n.id)} {json.dumps(one_line(n.name))} ({n.type}) ──"


def _model(wf: Workflow, n: Node) -> str:
    """`run.model("<model block>", temperature=...)` for the block's wired model."""
    models = wf.wired_into(n.id, "model")
    if not models:
        raise ValueError(f"'{n.name}' needs an AI model")
    m = models[0]
    settings = [f", {k}={_py(v)}" for k, v in model_settings(m).items()]
    return f"run.model({_py(m.name)}{''.join(settings)})"


def _step(wf: Workflow, n: Node, fn: str, names: _Names, dialect: Dialect) -> tuple[str, str]:
    """The code of one block (and any output classes it declares)."""
    c = n.config
    head = f"{_marker(n)}\nasync def {fn}(state: dict[str, Any], run: rt.Run) -> dict[str, Any]:\n"
    if n.type in ("core.router", "core.join"):
        return "", ""  # a path or "wait for all" changes nothing: FLOW says what follows
    if n.type == "core.set":
        items = ", ".join(
            f"{_py(k)}: " + (f"rt.render({_lit(v)}, state)" if isinstance(v, str) else _py(v))
            for k, v in (c.get("values") or {}).items()
        )
        return head + f"    return {{{items}}}", ""
    if n.type == "core.llm":
        prompt = names.take(f"{n.name}_prompt".upper())
        return (
            f"{prompt} = {_lit(c['prompt'])}\n\n\n" + head
            + f"    agent = {dialect.text_agent(n.name, _model(wf, n))}\n"
            + f"    return {{{_py(c['output'])}: await run.text(agent, rt.render({prompt}, state))}}"
        ), ""  # fmt: skip
    if n.type == "core.agent":
        return _agent(wf, n, fn, names, head, dialect)
    if n.type == "core.decide":
        prompt, choices = names.take(f"{n.name}_prompt".upper()), names.take(f"{n.name}_choices".upper())
        options = {case["route"]: case.get("description", "") for case in c.get("cases", [])}
        return (
            f"{prompt} = {_lit(c['prompt'])}\n{choices} = {_py(options)}\n\n\n" + head
            + f"    agent = {dialect.text_agent(n.name, _model(wf, n))}\n"
            + f"    reply = await run.text(agent, run.decide_prompt(rt.render({prompt}, state), {choices}))\n"
            + f"    return run.decision(reply, {choices}, output={_py(c['output'])})"
        ), ""  # fmt: skip
    if n.type == "core.approval":
        return head + f"    return run.approval(state, show={_py(c['show'])}, output={_py(c['output'])})", ""
    if n.type == "core.human_input":
        schema = f", schema={_py(c['response_schema'])}" if c.get("response_schema") else ""
        return head + f"    return run.ask(state, prompt={_lit(c['prompt'])}, output={_py(c['output'])}{schema})", ""
    if n.type == "core.script":
        return head + f"    return await run.script({_py(c['import_path'])}, state)", ""
    if n.type == "knowledge.search":
        kw = [f"output={_py(c.get('output', 'passages'))}"]
        kw += [f"mode={_py(c['mode'])}"] if c.get("mode", "hybrid") != "hybrid" else []
        kw += [f"top_k={_py(c['top_k'])}"] if c.get("top_k", 5) != 5 else []
        kw += [f"min_score={_py(c['min_score'])}"] if c.get("min_score") else []
        kw += [f"sources_output={_py(c['sources_output'])}"] if c.get("sources_output") else []
        query = c.get("query", "{{ state.question }}")
        return head + (
            f"    return await run.search(\n        {_py(c['knowledge_base'])}, rt.render({_lit(query)}, state), "
            + ", ".join(kw) + ",\n    )"
        ), ""  # fmt: skip
    raise NotImplementedError(f"a {dialect.label} flow cannot run '{n.type}' blocks")


def _agent(wf: Workflow, n: Node, fn: str, names: _Names, head: str, dialect: Dialect) -> tuple[str, str]:
    c = n.config
    schema = c.get("response_format")
    structured = bool(schema) and designs.schema_problem(schema) is None
    instructions = names.take(f"{n.name}_instructions".upper())
    builder = names.take(f"{n.name}_agent")
    answer = names.take(f"{_camel(n.name)}Answer") if structured else ""
    models = designs.output_models(schema, answer) if structured and schema else ""
    limit, fail = None, False
    for mw in wf.wired_into(n.id, "middleware"):
        if mw.type == "mw.model_call_limit":
            limit, fail = int(mw.config.get("run_limit", 20)), mw.config.get("exit_behavior") == "error"
    spec = Agentic(
        name=n.name, model=_model(wf, n), instructions=instructions,
        tools=[r.name for r in wf.wired_into(n.id, "tools")], approve=[t for t in c.get("approve_tools") or [] if t],
        answer=answer, call_limit=limit, fail_at_limit=fail,
    )  # fmt: skip
    args, run_kw = dialect.agent(spec)
    cls = dialect.agent_class
    body = ",\n".join(f"        {a}" for a in args)
    code = (
        f"{instructions} = {_lit(c.get('system_prompt') or 'Help the user.')}\n\n\n"
        + (f"{models}\n\n\n" if models else "")
        + f"def {builder}(run: rt.Run) -> {cls}:\n    return {cls}(\n{body},\n    )\n\n\n"
        + head
        + f'    return await run.agent({builder}(run), state.get("messages"){", structured=True" if structured else ""}'
        + f"{run_kw})"
    )
    return code, models


def tools_arg(a: Agentic) -> list[str]:
    if not a.tools:
        return []
    return [f"tools=run.tools({_py(a.tools)}" + (f", approve={_py(a.approve)})" if a.approve else ")")]


def _flow(wf: Workflow, fns: dict[str, str]) -> str:
    steps, nexts = [], []
    for n in wf.nodes:
        kw = [_py(n.name), _py(n.type)]
        if n.id in fns:
            kw.append(fns[n.id])
        if n.type == "core.router":
            cases = [(case["when"], case["route"]) for case in n.config.get("cases", [])]
            kw.append(f"cases={_py(cases)}")
        if n.type == "core.decide":
            kw.append(f"decides={_py(n.config['output'])}")
            if n.config.get("min_confidence") is not None:
                kw.append(f"min_confidence={_py(n.config['min_confidence'])}")
        if n.type in ("core.router", "core.decide") and n.config.get("default", "default") != "default":
            kw.append(f"default={_py(n.config['default'])}")
        if n.disabled:
            kw.append("disabled=True")
        marker = f"  # @canvas-node {one_line(n.id)} ({n.type})" if n.id not in fns else ""
        steps.append(f"        {_py(n.id)}: rt.Step({', '.join(kw)}),{marker}")
    for n in wf.nodes:
        edges = [e for e in wf.flow_edges() if e.source.node == n.id and e.target.node != "END"]
        if n.type in ("core.router", "core.decide"):
            routes: dict[str, list[str]] = {}
            for e in [e for e in wf.flow_edges() if e.source.node == n.id]:
                targets = routes.setdefault(e.source.route, [])
                if e.target.node != "END" and e.target.node not in targets:
                    targets.append(e.target.node)
            nexts.append(f"        {_py(n.id)}: {_py(routes)},")
        elif edges:
            nexts.append(f"        {_py(n.id)}: {_py(list(dict.fromkeys(e.target.node for e in edges)))},")
    start = list(dict.fromkeys(e.target.node for e in wf.flow_edges()
                               if e.source.node == "START" and e.target.node != "END"))  # fmt: skip
    channels = [f"        {_py(ch.name)}: ({_py(ch.reducer)}, {_py(ch.default)})," for ch in wf.state.channels]
    wanted = wf.settings.output_channels
    if wanted is None:
        wanted = [ch.name for ch in wf.state.channels if ch.io != "private"]
    return "\n".join(
        [
            "FLOW = rt.Flow(",
            f"    name={_py(wf.name)},",
            "    steps={",
            *steps,
            "    },",
            f"    start={_py(start)},",
            *(["    next={", *nexts, "    },"] if nexts else ["    next={},"]),
            "    channels={",
            *channels,
            "    },",
            f"    outputs={_py(wanted)},",
            f"    recursion_limit={wf.settings.recursion_limit},",
            ")",
        ]
    )
