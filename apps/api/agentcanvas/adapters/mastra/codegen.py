"""Workflow -> a TypeScript module with a Mastra flow (S36).

The module reads like code a person would write with Mastra: a Mastra `Agent` for each AI block (a model, its
instructions, `createTool` tools with `requireApproval` for the ones a person approves first, a Zod schema for typed
answers), one `async function` per block of the canvas (marked with `@canvas-node` so the code view jumps back to the
block), and a `FLOW` that says which step follows which. The flow engine (`flow.ts`, the TypeScript twin of
`supersteps`) runs it as the canvas draws it, and `runtime.ts` adds the Mastra parts. Node.js 22.18+ runs the module
as it is: it only uses types that can be stripped.
"""

