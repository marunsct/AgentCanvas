RESERVED = {
    "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do", "else", "enum",
    "export", "extends", "false", "finally", "for", "function", "if", "import", "in", "instanceof", "new", "null",
    "return", "super", "switch", "this", "throw", "true", "try", "typeof", "var", "void", "while", "with", "yield",
    "let", "static", "implements", "interface", "package", "private", "protected", "public", "await", "async",
    "arguments", "eval", "undefined", "NaN", "Infinity", "Object", "Array", "String", "Number", "Boolean", "Promise",
    "JSON", "Math", "Date", "Error", "Map", "Set", "Symbol", "console", "process",
    "rt", "Agent", "z", "FLOW", "state", "run",
}  # fmt: skip


def _js(value: Any) -> str:
    """A TypeScript literal for a JSON value."""
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{_key(k)}: {_js(v)}" for k, v in value.items()) + " }" if value else "{}"
    if isinstance(value, list | tuple):
        return "[" + ", ".join(_js(v) for v in value) + "]"
    return json.dumps(value, ensure_ascii=False)


def _key(name: str) -> str:
    return name if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", name) else json.dumps(name, ensure_ascii=False)


def _text(value: str) -> str:
    """A string literal: a template literal for text with line breaks when that reads better."""
    if "\n" in value and not re.search(r"[`\\]|\$\{|\r", value):
        return "`" + value + "`"
    return json.dumps(value, ensure_ascii=False)


def _words(name: str) -> list[str]:
    return [p for p in re.split(r"[^A-Za-z0-9]+", name) if p]


class _Names:
    def __init__(self) -> None:
        self.used: set[str] = set(RESERVED)

    def take(self, wanted: str, style: str = "camel") -> str:
        """A unique name: camelCase (functions), PascalCase (schemas) or UPPER_CASE (constants)."""
        words = _words(wanted) or ["step"]
        if style == "upper":
            name = "_".join(w.upper() for w in words)
        elif style == "pascal":
            name = "".join(w[:1].upper() + w[1:] for w in words)
        else:
            name = words[0][:1].lower() + words[0][1:] + "".join(w[:1].upper() + w[1:] for w in words[1:])
        if name[0].isdigit():
            name = f"step{name}" if style == "camel" else f"S{name}"
        base, i = name, 2
        while name in self.used:
            name, i = f"{base}{i}", i + 1
        self.used.add(name)
        return name


def generate(wf: Workflow) -> str:
    names = _Names()
    fns = {n.id: names.take(n.name) for n in wf.nodes if n.type not in ("core.router", "core.join")}
    blocks = [code for n in wf.nodes if (code := _step(wf, n, fns.get(n.id, ""), names))]
    uses_zod = any("z.object(" in b for b in blocks)
    uses_agent = any("new Agent(" in b for b in blocks)
    head = [
        "/**",
        f" * {one_line(wf.name)}: a Mastra flow, generated by AgentCanvas.",
        " *",
        " * Each block of the canvas is one step below (its id is in the `@canvas-node` comment), and FLOW at the",
        " * end says which step follows which. AI blocks are Mastra `Agent`s run with `agent.generate`; the other",
        " * blocks are plain TypeScript. `run` gives each step its models, tools and knowledge bases, and asks people",
        " * when a step needs them. Change the workflow on the canvas and generate it again rather than editing this",
        " * file.",
        " */",
        "",
        *(['import { Agent } from "@mastra/core/agent";'] if uses_agent else []),
        *(['import { z } from "zod";'] if uses_zod else []),
        *([""] if uses_agent or uses_zod else []),
        'import * as rt from "./runtime.ts";',
    ]
    return "\n".join(head) + "\n\n" + "\n\n".join([*blocks, _flow(wf, fns)]) + "\n"


def _marker(n: Node) -> str:
    return f"// ── @canvas-node {n.id} {json.dumps(one_line(n.name))} ({n.type}) ──"


def _model(wf: Workflow, n: Node) -> str:
    """`run.model("<model block>", { temperature: ... })` for the block's wired model."""
    models = wf.wired_into(n.id, "model")
    if not models:
        raise ValueError(f"'{n.name}' needs an AI model")
    m = models[0]
    settings = {k: m.config[k] for k in ("temperature", "max_tokens") if m.config.get(k) is not None}
    if "max_tokens" in settings:
        settings["maxTokens"] = settings.pop("max_tokens")
    return f"run.model({_js(m.name)}" + (f", {_js(settings)})" if settings else ")")


def _agent_id(name: str) -> str:
    return "-".join(w.lower() for w in _words(name)) or "agent"


def _step(wf: Workflow, n: Node, fn: str, names: _Names) -> str:
    """The code of one block."""
    c = n.config
    if n.type in ("core.router", "core.join"):
        return ""  # a path or "wait for all" changes nothing: FLOW says what follows
    head = f"{_marker(n)}\nexport async function {fn}(state: rt.State, run: rt.Run): Promise<rt.Update> {{\n"
    if n.type == "core.set":
        items = ", ".join(
            f"{_js(k)}: " + (f"rt.render({_text(v)}, state)" if isinstance(v, str) else _js(v))
            for k, v in (c.get("values") or {}).items()
        )
        return head + f"  return {{ {items} }};\n}}" if items else head + "  return {};\n}"
    if n.type == "core.llm":
        prompt = names.take(f"{n.name}_prompt", "upper")
        agent = (
            f'new Agent({{ id: {_js(_agent_id(n.name))}, name: {_js(n.name)}, instructions: "", '
            f"model: {_model(wf, n)} }})"
        )
        return (
            f"const {prompt} = {_text(c['prompt'])};\n\n" + head
            + f"  const agent = {agent};\n"
            + f"  return {{ {_js(c['output'])}: await run.text(agent, rt.render({prompt}, state)) }};\n}}"
        )  # fmt: skip
    if n.type == "core.agent":
        return _agent(wf, n, names, head)
    if n.type == "core.approval":
        return head + f"  return run.approval(state, {{ show: {_js(c['show'])}, output: {_js(c['output'])} }});\n}}"
    if n.type == "core.human_input":
        schema = f", schema: {_js(c['response_schema'])}" if c.get("response_schema") else ""
        return head + (
            f"  return run.ask(state, {{ prompt: {_text(c['prompt'])}, output: {_js(c['output'])}{schema} }});\n}}"
        )
    if n.type == "core.script":
        return head + f"  return await run.script({_js(c['import_path'])}, state);\n}}"
    if n.type == "knowledge.search":
        opts: dict[str, Any] = {"output": c.get("output", "passages")}
        if c.get("mode", "hybrid") != "hybrid":
            opts["mode"] = c["mode"]
        if c.get("top_k", 5) != 5:
            opts["top_k"] = c["top_k"]
        if c.get("min_score"):
            opts["min_score"] = c["min_score"]
        if c.get("sources_output"):
            opts["sources_output"] = c["sources_output"]
        query = c.get("query", "{{ state.question }}")
        return head + (
            f"  return await run.search({_js(c['knowledge_base'])}, rt.render({_text(query)}, state), {_js(opts)});\n}}"
        )
    raise NotImplementedError(f"a Mastra flow cannot run '{n.type}' blocks")


def _agent(wf: Workflow, n: Node, names: _Names, head: str) -> str:
    c = n.config
    schema = c.get("response_format")
    structured = bool(schema) and designs.schema_problem(schema) is None
    instructions = names.take(f"{n.name}_instructions", "upper")
    builder = names.take(f"{n.name}_agent")
    answer = names.take(f"{n.name}_answer", "pascal") if structured else ""
    tools = [r.name for r in wf.wired_into(n.id, "tools")]
    approve = [t for t in c.get("approve_tools") or [] if t]
    args = [
        f"id: {_js(_agent_id(n.name))}",
        f"name: {_js(n.name)}",
        f"instructions: {instructions}",
        f"model: {_model(wf, n)}",
    ]
    if tools:
        args.append(f"tools: run.tools({_js(tools)}" + (f", {{ approve: {_js(approve)} }})" if approve else ")"))
    opts: list[str] = []
    if structured:
        opts.append(f"answer: {answer}")
    for mw in wf.wired_into(n.id, "middleware"):
        if mw.type == "mw.model_call_limit":  # Mastra's own `maxSteps`: model calls in one turn
            opts.append(f"maxCalls: {int(mw.config.get('run_limit', 20))}")
            if mw.config.get("exit_behavior") == "error":
                opts.append("stopAtLimit: false")
    body = ",\n".join(f"    {a}" for a in args)
    return (
        f"const {instructions} = {_text(c.get('system_prompt') or 'Help the user.')};\n\n"
        + (f"const {answer} = {zod(schema or {})};\n\n" if structured else "")
        + f"function {builder}(run: rt.Run): Agent {{\n  return new Agent({{\n{body},\n  }});\n}}\n\n"
        + head
        + f"  return await run.agent({builder}(run), state.messages"
        + (f", {{ {', '.join(opts)} }}" if opts else "")
        + ");\n}"
    )


def zod(schema: dict[str, Any], indent: int = 0) -> str:
    """A Zod schema for a JSON Schema (as `designs.schema_problem` accepts them)."""
    pad = "  " * (indent + 1)
    if "enum" in schema:
        values = schema["enum"]
        out = (
            f"z.enum({_js(values)})" if all(isinstance(v, str) for v in values)
            else "z.union([" + ", ".join(f"z.literal({_js(v)})" for v in values) + "])"
        )  # fmt: skip
    else:
        t = schema.get("type")
        nullable = isinstance(t, list) and "null" in t
        if isinstance(t, list):
            t = next((x for x in t if x != "null"), "string")
        if t == "object" and schema.get("properties"):
            required = set(schema.get("required") or [])
            fields = [
                f"{pad}{_key(k)}: {zod(v, indent + 1)}{'' if k in required else '.optional()'},"
                for k, v in schema["properties"].items()
            ]
            out = "z.object({\n" + "\n".join(fields) + "\n" + "  " * indent + "})"
        elif t == "object":
            out = "z.record(z.string(), z.any())"
        elif t == "array":
            out = f"z.array({zod(schema.get('items') or {'type': 'string'}, indent)})"
        else:
            out = {"string": "z.string()", "integer": "z.number().int()", "number": "z.number()",
                   "boolean": "z.boolean()"}.get(str(t), "z.any()")  # fmt: skip
        if nullable:
            out += ".nullable()"
    if schema.get("description"):
        out += f".describe({_js(schema['description'])})"
    return out


def _flow(wf: Workflow, fns: dict[str, str]) -> str:
    steps, nexts = [], []
    for n in wf.nodes:
        kw = [f"name: {_js(n.name)}", f"type: {_js(n.type)}"]
        if n.id in fns:
            kw.append(f"run: {fns[n.id]}")
        if n.type == "core.router":
            cases = [[case["when"], case["route"]] for case in n.config.get("cases", [])]
            kw.append(f"cases: {_js(cases)}")
            if n.config.get("default", "default") != "default":
                kw.append(f"default: {_js(n.config['default'])}")
        if n.disabled:
            kw.append("disabled: true")
        marker = f" // @canvas-node {n.id} ({n.type})" if n.id not in fns else ""
        steps.append(f"    {_js(n.id)}: {{ {', '.join(kw)} }},{marker}")
    for n in wf.nodes:
        edges = [e for e in wf.flow_edges() if e.source.node == n.id and e.target.node != "END"]
        if n.type == "core.router":
            routes: dict[str, list[str]] = {}
            for e in [e for e in wf.flow_edges() if e.source.node == n.id]:
                targets = routes.setdefault(e.source.route, [])
                if e.target.node != "END" and e.target.node not in targets:
                    targets.append(e.target.node)
            nexts.append(f"    {_js(n.id)}: {_js(routes)},")
        elif edges:
            nexts.append(f"    {_js(n.id)}: {_js(list(dict.fromkeys(e.target.node for e in edges)))},")
    start = list(dict.fromkeys(e.target.node for e in wf.flow_edges()
                               if e.source.node == "START" and e.target.node != "END"))  # fmt: skip
    channels = [f"    {_key(ch.name)}: [{_js(ch.reducer)}, {_js(ch.default)}]," for ch in wf.state.channels]
    wanted = wf.settings.output_channels
    if wanted is None:
        wanted = [ch.name for ch in wf.state.channels if ch.io != "private"]
    return "\n".join(
        [
            "export const FLOW: rt.Flow = {",
            f"  name: {_js(wf.name)},",
            "  steps: {",
            *steps,
            "  },",
            f"  start: {_js(start)},",
            *(["  next: {", *nexts, "  },"] if nexts else ["  next: {},"]),
            "  channels: {",
            *channels,
            "  },",
            f"  outputs: {_js(wanted)},",
            f"  recursionLimit: {wf.settings.recursion_limit},",
            "};",
        ]
    )
