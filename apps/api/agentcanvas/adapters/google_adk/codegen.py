"""Workflow -> a Python module with a native Google ADK 2 graph workflow (S29).

The module reads like code a person would write with ADK: one function node per block of the canvas (marked with
`@canvas-node` so the code view jumps back to the block), an `Agent` builder per AI agent block, and a `build()`
that wires them with ADK's own edges: `("START", first)`, a route dict after each path block, a tuple where a step
fans out to parallel branches and a `JoinNode` where the canvas waits for every branch. `@rt.step` (see `runtime`)
adds what the canvas needs: events, field reducers, pauses for people and a loop guard.
"""

from __future__ import annotations

import builtins
import json
import keyword
import re

from agentcanvas import designs
from agentcanvas.adapters.langchain.codegen import doc_line, one_line
from agentcanvas.adapters.openai_agents.codegen import _camel, _lit, _py, model_settings
from agentcanvas.ir.contract import output_names
from agentcanvas.ir.models import Node, Workflow

ADK_VERSION = "2.14.0"
LITELLM_VERSION = "1.105.7"
RUNTIME_IMPORT = "from agentcanvas.adapters.google_adk import runtime as rt"
STEP_TYPES = {
    "core.set", "core.router", "core.join", "core.approval", "core.human_input", "core.script", "core.llm",
    "core.agent", "knowledge.search", "core.decide",
}  # fmt: skip
RESOURCE_TYPES = {"model.chat", "tool.python", "mw.model_call_limit"}
MODEL_CALLS = 20  # an agent's model calls in one turn, unless a model call limit block says otherwise
_TAKEN = {"rt", "Agent", "Workflow", "JoinNode", "BaseModel", "Field", "Any", "Literal", "CANVAS", "START", "build",
          "annotations", "user"}  # fmt: skip


class _Names:
    def __init__(self) -> None:
        self.used: set[str] = set(_TAKEN)

    def take(self, wanted: str) -> str:
        name = _ident(wanted)
        if keyword.iskeyword(name) or hasattr(builtins, name) or name in self.used or name.startswith("_"):
            name = f"{name.lstrip('_')}_step"
        i = 2
        base = name
        while name in self.used:
            name, i = f"{base}{i}", i + 1
        self.used.add(name)
        return name


def _ident(name: str) -> str:
    out = re.sub(r"\W+", "_", name.strip()).strip("_") or "step"
    return f"step_{out}" if out[0].isdigit() else out


def generate(wf: Workflow) -> str:
    names = _Names()
    fns = {n.id: names.take(n.name) for n in wf.nodes}
    waits = {n.id: names.take(f"{fns[n.id]}_wait") for n in wf.nodes if n.type == "core.join"}
    helpers: list[str] = []
    steps: list[str] = []
    pydantic_names: set[str] = set()
    typing_names: set[str] = set()
    for n in wf.nodes:
        helper, body, models = _step(wf, n, names)
        if helper:
            helpers.append(helper)
        if models:
            pydantic_names |= {"BaseModel"} | ({"Field"} if "Field(" in models else set())
            typing_names |= {t for t in ("Literal",) if re.search(rf"\b{t}\[", models)}
        steps.append(_function(n, fns[n.id], body))
    adk_names = ["Workflow"] + (["Agent"] if any("Agent(" in h for h in helpers) else [])
    head = [
        f'"""{doc_line(wf.name)}: a Google ADK workflow, generated by AgentCanvas.',
        "",
        "Each block of the canvas is a function node (its id is in the `@canvas-node` comment) and `build()` wires",
        "them with ADK's graph edges. `@rt.step` runs each function as the canvas does: it merges the fields a step",
        "returns into `run.state`, pauses for people and reports progress. `CANVAS` at the end says which fields the",
        "workflow has and returns. Change the workflow on the canvas and generate it again rather than editing this",
        "file.",
        '"""',
        "",
        "from typing import " + ", ".join(sorted({"Any", *typing_names})),
        "",
        f"from google.adk import {', '.join(sorted(adk_names))}",
        *(["from google.adk.workflow import JoinNode"] if waits else []),
        *([f"from pydantic import {', '.join(sorted(pydantic_names))}"] if pydantic_names else []),
        "",
        RUNTIME_IMPORT,
    ]
    parts = [*helpers, *steps, _build(wf, fns, waits), _canvas(wf)]
    return "\n".join(head) + "\n\n\n" + "\n\n\n".join(parts) + "\n"


def _marker(n: Node) -> str:
    return f"# ── @canvas-node {one_line(n.id)} {json.dumps(one_line(n.name))} ({n.type}) ──"


def _function(n: Node, fn: str, body: str) -> str:
    step_args = _py(n.id) + (", disabled=True" if n.disabled else "")
    returns = {"core.router": "str", "core.decide": "tuple[dict[str, Any], str]"}.get(n.type, "dict[str, Any]")
    return "\n".join([
        _marker(n),
        f"@rt.step({step_args})",
        f"async def {fn}(run: rt.Run) -> {returns}:",
        *[f"    {line}" if line else "" for line in body.split("\n")],  # so strings in a body are one-line (`_py`)
    ])  # fmt: skip


def _build(wf: Workflow, fns: dict[str, str], waits: dict[str, str]) -> str:
    """`build()`: the ADK workflow's edges, from the canvas's flow edges."""
    routers = {n.id for n in wf.nodes if n.type in ("core.router", "core.decide")}

    def target(node_id: str) -> str | None:
        if node_id not in fns:
            return None  # END
        return waits.get(node_id, fns[node_id])

    def group(targets: list[str]) -> str:
        return targets[0] if len(targets) == 1 else f"({', '.join(targets)})"

    outgoing: dict[str, list[tuple[str | None, str]]] = {}
    for e in wf.flow_edges():
        dst = target(e.target.node)
        if dst is None:
            continue
        route = (e.source.port or "").removeprefix("route:") if e.source.node in routers else None
        found = outgoing.setdefault(e.source.node, [])
        if (route, dst) not in found:
            found.append((route, dst))
    edges: list[str] = []
    order = ["START", *(n.id for n in wf.nodes)]
    for src in order:
        if src not in outgoing:
            continue
        name = '"START"' if src == "START" else fns[src]
        if src in routers:
            by_route: dict[str, list[str]] = {}
            for route, dst in outgoing[src]:
                by_route.setdefault(route or "default", []).append(dst)
            cases = ", ".join(f"{_py(r)}: {group(ts)}" for r, ts in by_route.items())
            edges.append(f"({name}, {{{cases}}})")
        else:
            edges.append(f"({name}, {group([dst for _, dst in outgoing[src]])})")
    edges += [f"({wait}, {fns[node_id]})" for node_id, wait in waits.items()]
    joins = [f"    {wait} = JoinNode(name={_py(wait)})" for wait in waits.values()]
    return "\n".join([
        "def build() -> Workflow:",
        '    """The workflow as an ADK graph: a node per block, joined as on the canvas."""',
        *joins,
        "    return Workflow(",
        f"        name={_py(_ident(wf.name).lower())},",
        "        edges=[",
        *[f"            {e}," for e in edges],
        "        ],",
        "    )",
    ])  # fmt: skip


def _llm(wf: Workflow, n: Node) -> str:
    """`run.llm("<model block>", temperature=...)` for the block's wired model."""
    models = wf.wired_into(n.id, "model")
    if not models:
        raise ValueError(f"'{n.name}' needs an AI model")
    m = models[0]
    settings = [f", {k}={_py(v)}" for k, v in model_settings(m).items()]
    return f"run.llm({_py(m.name)}{''.join(settings)})"


def _step(wf: Workflow, n: Node, names: _Names) -> tuple[str, str, str]:
    """(module-level code the step needs, the function body, output classes) of one block."""
    c = n.config
    if n.type == "core.router":
        cases = [(case["when"], case["route"]) for case in c.get("cases", [])]
        default = c.get("default", "default")
        tail = f", default={_py(default)})" if default != "default" else ")"
        return "", f"return run.route({_py(cases)}{tail}", ""
    if n.type == "core.join":
        return "", '"""Goes on once every branch has finished (its JoinNode waits for them)."""\nreturn {}', ""
    if n.type == "core.decide":
        prompt, choices = names.take(f"{n.name}_prompt".upper()), names.take(f"{n.name}_choices".upper())
        options = {case["route"]: case.get("description", "") for case in c.get("cases", [])}
        kw = [f"output={_py(c['output'])}"]
        kw += [f"default={_py(c['default'])}"] if c.get("default", "default") != "default" else []
        kw += [f"min_confidence={_py(c['min_confidence'])}"] if c.get("min_confidence") is not None else []
        return (
            f"{prompt} = {_lit(c['prompt'])}\n{choices} = {_py(options)}",
            f"reply = await run.text({_llm(wf, n)}, run.decide_prompt(rt.render({prompt}, run.state), {choices}))\n"
            f"return run.decide(reply, {choices}, {', '.join(kw)})",
            "",
        )
    if n.type == "core.set":
        items = ", ".join(
            f"{_py(k)}: " + (f"rt.render({_py(v)}, run.state)" if isinstance(v, str) else _py(v))
            for k, v in (c.get("values") or {}).items()
        )
        return "", f"return {{{items}}}", ""
    if n.type == "core.llm":
        prompt = names.take(f"{n.name}_prompt".upper())
        return (
            f"{prompt} = {_lit(c['prompt'])}",
            f"return {{{_py(c['output'])}: await run.text({_llm(wf, n)}, rt.render({prompt}, run.state))}}",
            "",
        )
    if n.type == "core.agent":
        return _agent(wf, n, names)
    if n.type == "core.approval":
        return "", f"return run.approval(show={_py(c['show'])}, output={_py(c['output'])})", ""
    if n.type == "core.human_input":
        schema = f", schema={_py(c['response_schema'])}" if c.get("response_schema") else ""
        return "", f"return run.ask(prompt={_py(c['prompt'])}, output={_py(c['output'])}{schema})", ""
    if n.type == "core.script":
        return "", f"return await run.script({_py(c['import_path'])})", ""
    if n.type == "knowledge.search":
        kw = [f"output={_py(c.get('output', 'passages'))}"]
        kw += [f"mode={_py(c['mode'])}"] if c.get("mode", "hybrid") != "hybrid" else []
        kw += [f"top_k={_py(c['top_k'])}"] if c.get("top_k", 5) != 5 else []
        kw += [f"min_score={_py(c['min_score'])}"] if c.get("min_score") else []
        kw += [f"sources_output={_py(c['sources_output'])}"] if c.get("sources_output") else []
        query = c.get("query", "{{ state.question }}")
        return "", (
            f"return await run.search(\n    {_py(c['knowledge_base'])}, rt.render({_py(query)}, run.state), "
            + ", ".join(kw) + ",\n)"
        ), ""  # fmt: skip
    raise NotImplementedError(f"a Google ADK workflow cannot run '{n.type}' blocks")


def _call_limit(wf: Workflow, n: Node) -> int:
    for mw in wf.wired_into(n.id, "middleware"):
        if mw.type == "mw.model_call_limit":  # model calls in one turn of the agent
            return int(mw.config.get("run_limit", MODEL_CALLS))
    return MODEL_CALLS


def _agent(wf: Workflow, n: Node, names: _Names) -> tuple[str, str, str]:
    c = n.config
    schema = c.get("response_format")
    structured = bool(schema) and designs.schema_problem(schema) is None
    instructions = names.take(f"{n.name}_instructions".upper())
    builder = names.take(f"{n.name}_agent")
    answer = names.take(f"{_camel(n.name)}Answer") if structured else ""
    models = designs.output_models(schema, answer) if structured and schema else ""
    tools = [r.name for r in wf.wired_into(n.id, "tools")]
    approve = [t for t in c.get("approve_tools") or [] if t]
    args = [
        f"name={_py(_ident(n.name))}",
        f"description={_py(one_line(n.label or n.name))}",
        f"model={_llm(wf, n)}",
        f"instruction=rt.literal({instructions})",
        *([f"tools=run.tools({_py(tools)}" + (f", approve={_py(approve)})" if approve else ")")] if tools else []),
        *([f"output_schema={answer}"] if structured else []),
        f"before_model_callback=run.call_limit({_call_limit(wf, n)})",
    ]
    body = ",\n".join(f"        {a}" for a in args)
    helper = (
        f"{instructions} = {_lit(c.get('system_prompt') or 'Help the user.')}\n\n\n"
        + (f"{models}\n\n\n" if models else "")
        + f"def {builder}(run: rt.Run) -> Agent:\n    return Agent(\n{body},\n    )"
    )
    flag = ", structured=True" if structured else ""
    return helper, f'return await run.agent({builder}(run), run.state.get("messages"){flag})', models


def _canvas(wf: Workflow) -> str:
    channels = [f"        {_py(ch.name)}: ({_py(ch.reducer)}, {_py(ch.default)})," for ch in wf.state.channels]
    steps = [f"        {_py(n.id)}: {_py(n.name)}," for n in wf.nodes]
    wanted = output_names(wf)
    return "\n".join(
        [
            "CANVAS = rt.Canvas(",
            "    build=build,",
            f"    name={_py(wf.name)},",
            "    steps={",
            *steps,
            "    },",
            "    channels={",
            *channels,
            "    },",
            f"    outputs={_py(wanted)},",
            f"    recursion_limit={wf.settings.recursion_limit},",
            ")",
        ]
    )
