"""Workflow -> a Python module for the OpenAI Agents SDK (S25).

The module reads like code a person would write with the SDK: an `Agent` builder per AI block, one `async def` per
block of the canvas (marked with `@canvas-node` so the code view jumps back to the block), and a `FLOW` that says
which step follows which. `runtime` runs it, inside AgentCanvas and in exports alike.
"""

from __future__ import annotations

import builtins
import json
import keyword
import re
from typing import Any

from agentcanvas import designs
from agentcanvas.adapters.langchain.codegen import doc_line, one_line
from agentcanvas.ir.models import Node, Resource, Workflow
from agentcanvas.sampling import without_sampling

SDK_VERSION = "0.24.0"
RUNTIME_IMPORT = "from agentcanvas.adapters.openai_agents import runtime as rt"
STEP_TYPES = {
    "core.set", "core.router", "core.join", "core.approval", "core.human_input", "core.script", "core.llm",
    "core.agent", "knowledge.search",
}  # fmt: skip
RESOURCE_TYPES = {"model.chat", "tool.python", "mw.model_call_limit"}
_TAKEN = {"rt", "Agent", "ModelSettings", "BaseModel", "Field", "Any", "Literal", "FLOW", "annotations"}


def _lit(value: Any) -> str:
    """A Python literal for a JSON value (strings with line breaks as triple-quoted text when that reads better)."""
    return designs.literal(value) if isinstance(value, str) else _py(value)


def _py(value: Any) -> str:
    """A Python literal for a JSON value, in the style of the code around it (double-quoted strings)."""
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, bool) or value is None:
        return repr(value)
    if isinstance(value, list | tuple):
        inner = ", ".join(_py(v) for v in value)
        return f"({inner}{',' if len(value) == 1 else ''})" if isinstance(value, tuple) else f"[{inner}]"
    if isinstance(value, dict):
        return "{" + ", ".join(f"{_py(k)}: {_py(v)}" for k, v in value.items()) + "}"
    return repr(value)


def model_settings(m: Resource) -> dict[str, Any]:
    """A model block's temperature and max_tokens, without the sampling settings its model refuses (W020): the
    provider would answer them with a 400."""
    found = {k: m.config[k] for k in ("temperature", "max_tokens") if m.config.get(k) is not None}
    return without_sampling(str(m.config.get("model", "")), found)[0]


def _camel(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in name.split("_") if p) or "Step"


class _Names:
    def __init__(self) -> None:
        self.used: set[str] = set(_TAKEN)

    def take(self, wanted: str) -> str:
        name = wanted
        if keyword.iskeyword(name) or hasattr(builtins, name) or name in self.used:
            name = f"{wanted}_step"
        i = 2
        while name in self.used:
            name, i = f"{wanted}_step{i}", i + 1
        self.used.add(name)
        return name


def generate(wf: Workflow) -> str:
    names = _Names()
    fns = {n.id: names.take(n.name) for n in wf.nodes if n.type not in ("core.router", "core.join")}
    blocks: list[str] = []
    uses_settings = False
    typing_names: set[str] = set()
    pydantic_names: set[str] = set()
    for n in wf.nodes:
        code, extra = _step(wf, n, fns.get(n.id, ""), names)
        if code:
            blocks.append(code)
        uses_settings |= "ModelSettings(" in code
        typing_names |= {t for t in ("Any", "Literal") if re.search(rf"\b{t}\[", extra)}
        if extra:
            pydantic_names |= {"BaseModel"} | ({"Field"} if "Field(" in extra else set())
    agents_names = ["Agent", *(["ModelSettings"] if uses_settings else [])]
    head = [
        f'"""{doc_line(wf.name)}: a flow for the OpenAI Agents SDK, generated by AgentCanvas.',
        "",
        "Each block of the canvas is one step below (its id is in the `@canvas-node` comment), and FLOW at the end",
        "says which step follows which. AI blocks are `Agent`s run with `Runner.run`; the other blocks are plain",
        "Python. `run` gives each step its models, tools and knowledge bases, and asks people when a step needs them.",
        "Change the workflow on the canvas and generate it again rather than editing this file.",
        '"""',
        "",
        "from typing import " + ", ".join(sorted({"Any", *typing_names})),
        "",
        f"from agents import {', '.join(agents_names)}",
        *([f"from pydantic import {', '.join(sorted(pydantic_names))}"] if pydantic_names else []),
        "",
        RUNTIME_IMPORT,
    ]
    return "\n".join(head) + "\n\n\n" + "\n\n\n".join([*blocks, _flow(wf, fns)]) + "\n"


def _marker(n: Node) -> str:
    return f"# ── @canvas-node {one_line(n.id)} {json.dumps(one_line(n.name))} ({n.type}) ──"


def _model(wf: Workflow, n: Node) -> tuple[str, str]:
    """`model=run.model("<resource>")` and the `model_settings=...` line for a block's wired model."""
    models = wf.wired_into(n.id, "model")
    if not models:
        return "", ""
    m = models[0]
    settings = [f"{k}={_py(v)}" for k, v in model_settings(m).items()]
    return f"run.model({_py(m.name)})", (f"ModelSettings({', '.join(settings)})" if settings else "")


def _step(wf: Workflow, n: Node, fn: str, names: _Names) -> tuple[str, str]:
    """The code of one block (and any output classes it declares)."""
    c = n.config
    head = f"{_marker(n)}\nasync def {fn}(state: dict[str, Any], run: rt.Run) -> dict[str, Any]:\n"
    if n.type in ("core.router", "core.join"):
        return "", ""  # a path or "wait for all" changes nothing: FLOW says what follows
    if n.type == "core.set":
        items = ", ".join(
            f"{_py(k)}: " + (f"rt.render({_lit(v)}, state)" if isinstance(v, str) else _py(v))
            for k, v in (c.get("values") or {}).items()
        )
        return head + f"    return {{{items}}}", ""
    if n.type == "core.llm":
        model, settings = _model(wf, n)
        prompt = names.take(f"{n.name}_prompt".upper())
        args = [f"name={_py(n.name)}", f"model={model}", *([f"model_settings={settings}"] if settings else [])]
        return (
            f"{prompt} = {_lit(c['prompt'])}\n\n\n" + head
            + f"    agent = Agent({', '.join(args)})\n"
            + f"    return {{{_py(c['output'])}: await run.text(agent, rt.render({prompt}, state))}}"
        ), ""  # fmt: skip
    if n.type == "core.agent":
        return _agent(wf, n, fn, names, head)
    if n.type == "core.approval":
        return head + f"    return run.approval(state, show={_py(c['show'])}, output={_py(c['output'])})", ""
    if n.type == "core.human_input":
        schema = f", schema={_py(c['response_schema'])}" if c.get("response_schema") else ""
        return head + f"    return run.ask(state, prompt={_lit(c['prompt'])}, output={_py(c['output'])}{schema})", ""
    if n.type == "core.script":
        return head + f"    return await run.script({_py(c['import_path'])}, state)", ""
    if n.type == "knowledge.search":
        kw = [f"output={_py(c.get('output', 'passages'))}"]
        kw += [f"mode={_py(c['mode'])}"] if c.get("mode", "hybrid") != "hybrid" else []
        kw += [f"top_k={_py(c['top_k'])}"] if c.get("top_k", 5) != 5 else []
        kw += [f"min_score={_py(c['min_score'])}"] if c.get("min_score") else []
        kw += [f"sources_output={_py(c['sources_output'])}"] if c.get("sources_output") else []
        query = c.get("query", "{{ state.question }}")
        return head + (
            f"    return await run.search(\n        {_py(c['knowledge_base'])}, rt.render({_lit(query)}, state), "
            + ", ".join(kw) + ",\n    )"
        ), ""  # fmt: skip
    raise NotImplementedError(f"the OpenAI Agents SDK flow cannot run '{n.type}' blocks")


def _agent(wf: Workflow, n: Node, fn: str, names: _Names, head: str) -> tuple[str, str]:
    c = n.config
    model, settings = _model(wf, n)
    tools = [r.name for r in wf.wired_into(n.id, "tools")]
    schema = c.get("response_format")
    structured = bool(schema) and designs.schema_problem(schema) is None
    instructions = names.take(f"{n.name}_instructions".upper())
    builder = names.take(f"{n.name}_agent")
    answer = names.take(f"{_camel(n.name)}Answer") if structured else ""
    models = designs.output_models(schema, answer) if structured and schema else ""
    args = [f"name={_py(n.name)}", f"instructions={instructions}", f"model={model}"]
    if settings:
        args.append(f"model_settings={settings}")
    if tools:
        approve = [t for t in c.get("approve_tools") or [] if t]
        args.append(f"tools=run.tools({_py(tools)}" + (f", approve={_py(approve)})" if approve else ")"))
    if structured:
        args.append(f"output_type={answer}")
    body = ",\n".join(f"        {a}" for a in args)
    run_kw = [", structured=True"] if structured else []
    for mw in wf.wired_into(n.id, "middleware"):
        if mw.type == "mw.model_call_limit":  # the SDK's max_turns: model calls in one run of the agent
            run_kw.append(f", max_turns={int(mw.config.get('run_limit', 20))}")
            if mw.config.get("exit_behavior") == "error":
                run_kw.append(", stop_at_limit=False")
    code = (
        f"{instructions} = {_lit(c.get('system_prompt') or '')}\n\n\n"
        + (f"{models}\n\n\n" if models else "")
        + f"def {builder}(run: rt.Run) -> Agent:\n    return Agent(\n{body},\n    )\n\n\n"
        + head
        + f"    return await run.agent({builder}(run), state.get('messages'){''.join(run_kw)})"
    )
    return code, models


def _flow(wf: Workflow, fns: dict[str, str]) -> str:
    steps, nexts = [], []
    for n in wf.nodes:
        kw = [repr(n.name), repr(n.type)]
        if n.id in fns:
            kw.append(fns[n.id])
        if n.type == "core.router":
            cases = [(case["when"], case["route"]) for case in n.config.get("cases", [])]
            kw.append(f"cases={_py(cases)}")
            if n.config.get("default", "default") != "default":
                kw.append(f"default={_py(n.config['default'])}")
        if n.disabled:
            kw.append("disabled=True")
        marker = f"  # @canvas-node {one_line(n.id)} ({n.type})" if n.id not in fns else ""
        steps.append(f"        {_py(n.id)}: rt.Step({', '.join(kw)}),{marker}")
    for n in wf.nodes:
        edges = [e for e in wf.flow_edges() if e.source.node == n.id and e.target.node != "END"]
        if n.type == "core.router":
            routes: dict[str, list[str]] = {}
            for e in [e for e in wf.flow_edges() if e.source.node == n.id]:
                targets = routes.setdefault(e.source.route, [])
                if e.target.node != "END":
                    targets.append(e.target.node)
            nexts.append(f"        {_py(n.id)}: {_py(routes)},")
        elif edges:
            nexts.append(f"        {_py(n.id)}: {_py([e.target.node for e in edges])},")
    start = [e.target.node for e in wf.flow_edges() if e.source.node == "START" and e.target.node != "END"]
    channels = [f"        {_py(ch.name)}: ({_py(ch.reducer)}, {_py(ch.default)})," for ch in wf.state.channels]
    wanted = wf.settings.output_channels
    if wanted is None:
        wanted = [ch.name for ch in wf.state.channels if ch.io != "private"]
    return "\n".join(
        [
            "FLOW = rt.Flow(",
            f"    name={_py(wf.name)},",
            "    steps={",
            *steps,
            "    },",
            f"    start={_py(start)},",
            *(["    next={", *nexts, "    },"] if nexts else ["    next={},"]),
            "    channels={",
            *channels,
            "    },",
            f"    outputs={_py(wanted)},",
            f"    recursion_limit={wf.settings.recursion_limit},",
            ")",
        ]
    )
