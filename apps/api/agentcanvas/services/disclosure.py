"""Marking AI-generated output (EU AI Act Art. 50(2)): what a published deployment answers is machine-readably marked
as produced by an AI system, so a caller's own systems can label it or keep it apart.

- every run response of the deployment API, MCP and A2A endpoints, and share-link stream carries `X-AI-Generated: true`;
- deployment API results and the final event of their stream carry `generated_by`: `{"kind": "ai", "models": [...]}`,
  the models that answered in the run (from its usage events), in the order they first answered. It is empty when no
  model was called; the output still comes from the published AI system, so it stays marked.
"""

from __future__ import annotations

from collections.abc import AsyncIterator, Iterable
from typing import Any, Literal

from pydantic import BaseModel, Field

AI_HEADER = {"X-AI-Generated": "true"}


class GeneratedBy(BaseModel):
    kind: Literal["ai"] = Field(default="ai", description="the output was generated by an AI system")
    models: list[str] = Field(
        default_factory=list, description="the models that answered in this run, e.g. anthropic:claude-sonnet-4-6"
    )


def model_of(event: dict[str, Any]) -> str | None:
    """The model a usage event (`ac.usage`) reports, if the event is one."""
    if event.get("type") != "CUSTOM" or event.get("name") != "ac.usage":
        return None
    value = event.get("value")
    model = value.get("model") if isinstance(value, dict) else None
    return model if isinstance(model, str) and model else None


def generated_by(events: Iterable[dict[str, Any]]) -> GeneratedBy:
    models: list[str] = []
    for ev in events:
        if (m := model_of(ev)) and m not in models:
            models.append(m)
    return GeneratedBy(models=models)


async def marked(events: AsyncIterator[dict[str, Any]]) -> AsyncIterator[dict[str, Any]]:
    """A run's event stream with `generated_by` on its RUN_FINISHED event (a copy: subscribers share the events)."""
    models: list[str] = []
    async for ev in events:
        if (m := model_of(ev)) and m not in models:
            models.append(m)
        elif ev.get("type") == "RUN_FINISHED":
            yield {**ev, "generated_by": GeneratedBy(models=list(models)).model_dump()}
            continue
        yield ev
