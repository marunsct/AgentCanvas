"""Export one Agent block as a native project for its framework (S21).

The project runs on its own: `agent.py` is the generated agent (the same code AgentCanvas runs), `agent_tools.py` its
tools as plain functions, `main.py` a terminal runner, and `tests/` checks it offline against a fake model server.
Python tools bring exactly the workspace code they import (as whole-workflow exports do).
"""

from __future__ import annotations

import io
import json
import re
import zipfile
from importlib import metadata
from pathlib import Path

from agentcanvas.designs import AGENT_FRAMEWORKS, AgentDesign, article, export_problems, generate
from agentcanvas.errors import InvalidInput
from agentcanvas.ir.models import SECRET_NAME, Workflow
from agentcanvas.workspace import bundle

KIT = Path(__file__).parent / "kit"


def _pin(dist: str) -> str:
    try:
        return f"{dist}=={metadata.version(dist)}"
    except metadata.PackageNotFoundError:
        return dist


def _secrets(value: object) -> set[str]:
    if isinstance(value, dict):
        if "$secret" in value and isinstance(value["$secret"], str):
            if not SECRET_NAME.fullmatch(value["$secret"]):  # each one is a line of .env.example
                raise InvalidInput(f"secret name {value['$secret']!r} is not a variable name (letters, digits and _)")
            return {value["$secret"]}
        return set().union(*(_secrets(v) for v in value.values())) if value else set()
    if isinstance(value, list):
        return set().union(*(_secrets(v) for v in value)) if value else set()
    return set()


_IMPORT_PATH = re.compile(r"[A-Za-z_]\w*(\.[A-Za-z_]\w*)*:[A-Za-z_]\w*")


def agent_tools(design: AgentDesign) -> str:
    """`agent_tools.py`: the agent's tools, loaded when it starts."""
    imports, lines = [], []
    for i, t in enumerate(design.tools):
        if t.type == "tool.python":
            path = str(t.config.get("import_path", ""))
            if not _IMPORT_PATH.fullmatch(path):  # it is written into the code as an import
                raise InvalidInput(f"tool '{t.resource}': import path {path!r} is not module.path:function")
            module, _, fn = path.partition(":")
            imports.append(f"from {module} import {fn} as _tool_{i}")  # aliased: two modules may share a name
            lines.append(f"    found.append(_tool_{i})")
        elif t.type == "tool.http":
            lines.append(f"    found.append(http_tool({json.dumps(t.resource)}, {t.config!r}))")
        else:
            args = [json.dumps(t.config.get("url", ""))]
            if t.config.get("headers"):
                args.append(f"headers={t.config['headers']!r}")
            if t.config.get("tool_filter"):
                args.append(f"only={t.config['tool_filter']!r}")
            lines.append(f"    found += await mcp_tools({', '.join(args)})")
    helpers = ["approval"] + (["http_tool"] if any(t.type == "tool.http" for t in design.tools) else [])
    helpers += ["mcp_tools"] if any(t.type == "mcp.server" for t in design.tools) else []
    body = "\n".join(lines) if lines else "    pass"
    return "\n".join([
        f'"""The tools of the agent "{design.name}", as plain Python functions (generated by AgentCanvas)."""',
        "",
        "from __future__ import annotations",
        "",
        f"from canvas_tools import {', '.join(sorted(helpers))}",
        *sorted(set(imports)),
        "",
        f"APPROVE = {json.dumps(sorted(design.approve_tools))}  # these ask on the terminal before they run",
        "",
        "",
        "async def load_tools() -> list:",
        '    """Every tool the agent may call (MCP servers are asked for their tools here)."""',
        "    found: list = []",
        body,
        "    return [approval(t) if t.__name__ in APPROVE else t for t in found]",
        "",
    ])  # fmt: skip


