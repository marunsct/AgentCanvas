def _readme(design: AgentDesign, framework: str, key_env: str, secrets: list[str], root: str) -> str:
    fw = AGENT_FRAMEWORKS[framework]
    m = design.model
    model = f"{m.provider}:{m.name}" if m else "the model"
    env = "\n".join([f"{key_env}=...", *[f"{s}=..." for s in secrets]])
    approvals = (
        f"\nTools that ask before they run (on the terminal): {', '.join(design.approve_tools)}.\n"
        if design.approve_tools
        else ""
    )
    intro = f"{article(fw.label).capitalize()} {fw.label}"
    return f"""# {design.name}

{intro} agent designed on AgentCanvas (block "{design.name}" of the workflow "{design.workflow}").
It uses {model} and {len(design.tools)} tool block(s).{approvals}

## Run it

```bash
cd {root}
uv sync                      # or: python -m venv .venv && pip install -e .
cp .env.example .env         # then fill in the keys
uv run --env-file .env python main.py "Hello!"
```

Without a question, `main.py` chats in the terminal. To use the agent from your own code:

```python
from agent import ask, build
from agent_tools import load_tools

agent = build(await load_tools())
print(await ask(agent, "Hello!"))
```

## Files

- `agent.py`: the agent in {fw.label}'s own style, generated from the canvas (the same code AgentCanvas runs).
  `MODEL_BASE_URL` overrides where it reaches the model.
- `agent_tools.py` and `canvas_tools.py`: its tools as plain Python functions.
- `tests/`: offline checks against a fake model server: `uv run pytest`.

## Settings

```
{env}
```
"""


def export_files(
    wf: Workflow, design: AgentDesign, framework: str, workspace: Path | None = None
) -> dict[str, str | bytes]:
    """The project's files by path. Raises InvalidInput (with every reason) when the design cannot be exported."""
    problems = export_problems(framework, design)
    if problems:
        raise InvalidInput("this agent cannot be exported for " + AGENT_FRAMEWORKS[framework].label + ": "
                           + "; ".join(problems))  # fmt: skip
    fw = AGENT_FRAMEWORKS[framework]
    assert design.model is not None
    name = re.sub(r"[^a-z0-9]+", "-", f"{design.name}-{framework}".lower()).strip("-")
    tools_src = agent_tools(design)
    deps = list(fw.packages)
    if any(t.type == "tool.http" for t in design.tools):
        deps.append(_pin("httpx"))
    if any(t.type == "mcp.server" for t in design.tools):
        deps.append(_pin("fastmcp"))
    files: dict[str, str | bytes] = {
        "agent.py": generate(framework, design),
        "agent_tools.py": tools_src,
        "canvas_tools.py": (KIT / "canvas_tools.py").read_text(),
        "main.py": MAIN,
        "tests/fake_model.py": (KIT / "fake_model.py").read_text(),
        "tests/test_agent.py": TESTS.format(
            base_url='root + "/v1"' if fw.api == "openai" else "root",
            has_mcp=any(t.type == "mcp.server" for t in design.tools),
            tool_names=[
                t.config["import_path"].partition(":")[2] if t.type == "tool.python" else t.resource
                for t in design.tools
                if t.type != "mcp.server"
            ],
        ),
        "tests/conftest.py": CONFTEST,
        ".gitignore": ".venv/\n__pycache__/\n.env\n",
    }
    if workspace is not None and design.tools:
        found = bundle.collect(workspace, wf.id, json.dumps([t.config for t in design.tools]))
        if found.missing:
            raise InvalidInput("the agent's tools use code that is not in the workspace: " + ", ".join(found.missing))
        for rel in found.files:
            files[rel] = (workspace / rel).read_bytes()
        deps += [r for r in found.requirements if r not in deps]
    secrets = sorted(_secrets([t.config for t in design.tools]))
    files[".env.example"] = (
        "\n".join([f"{design.model.key_env}=", "# MODEL_BASE_URL=", *[f"{s}=" for s in secrets]]) + "\n"
    )
    files["README.md"] = _readme(design, framework, design.model.key_env, secrets, name)
    files["pyproject.toml"] = "\n".join([
        "[project]",
        f'name = "{name}"',
        'version = "0.1.0"',
        f'description = {json.dumps(f"{design.name}: {article(fw.label)} {fw.label} agent designed on AgentCanvas")}',
        'requires-python = ">=3.11"',
        "dependencies = [",
        *[f'    "{d}",' for d in deps],
        "]",
        "",
        "[dependency-groups]",
        f'dev = ["{_pin("pytest")}"]',
        "",
        "[tool.uv]",
        "package = false",
        "",
    ])  # fmt: skip
    return {f"{name}/{rel}": text for rel, text in files.items()}


def export_zip(wf: Workflow, design: AgentDesign, framework: str, workspace: Path | None = None) -> tuple[str, bytes]:
    files = export_files(wf, design, framework, workspace)
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for rel, content in sorted(files.items()):
            info = zipfile.ZipInfo(rel, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, content)
    return f"{next(iter(files)).split('/')[0]}.zip", buf.getvalue()
